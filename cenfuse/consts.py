"""Every numeric constant cenfuse decides with, and its reason, read from the code (future.md #64).

A constant is a module-level UPPER_CASE name bound to a number, a tuple of numbers or arithmetic on them, plus every field of the
satellite engine's Params with its sat/params.REASON line. Its reason is the comment on its line, the comment lines right
below it (continuations) or, failing those, right above it. Reasons that say 'heuristic' or 'prior' are marked, so the
named heuristics and the absolute priors stay visible. design.md's Constants table is the curated summary; docs/constants.md
is this complete list, regenerated by `python -m cenfuse.consts docs/constants.md` and checked by tests/fuse/test_constants.py.
Layout constants of the figures are listed too (marked 'layout')."""
from __future__ import annotations

import ast
import re
import sys
from dataclasses import fields
from pathlib import Path

PKG = Path(__file__).parent


def _numeric(v) -> bool:
    if isinstance(v, ast.Constant):
        return isinstance(v.value, (int, float)) and not isinstance(v.value, bool)
    if isinstance(v, (ast.Tuple, ast.List)):
        return bool(v.elts) and all(_numeric(e) for e in v.elts)
    if isinstance(v, ast.BinOp):
        return _numeric(v.left) and _numeric(v.right)
    if isinstance(v, ast.UnaryOp):
        return _numeric(v.operand)
    return False


def _comment(line: str) -> str:
    """The comment of a source line ('' if none), ignoring '#' inside string literals."""
    out, quote = None, None
    for i, ch in enumerate(line):
        if quote:
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif ch == "#":
            out = line[i + 1:]
            break
    return (out or "").strip()


def scan(pkg: Path = PKG) -> list:
    """[(module, line, name, value source, reason)] for every module-level numeric constant of the package, sorted."""
    rows = []
    for f in sorted(pkg.rglob("*.py")):
        src = f.read_text()
        lines = src.splitlines()
        for node in ast.parse(src).body:
            if not isinstance(node, (ast.Assign, ast.AnnAssign)) or node.value is None or not _numeric(node.value):
                continue
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names = [t.id for t in targets if isinstance(t, ast.Name)]
            if not names or not all(n.lstrip("_").isupper() for n in names):
                continue
            i, j = node.lineno - 1, node.end_lineno - 1
            parts = [_comment(lines[k]) for k in range(i, j + 1)]
            k = j + 1
            while k < len(lines) and lines[k].strip().startswith("#") and lines[k].startswith(" "):
                parts.append(lines[k].strip()[1:].strip())
                k += 1
            reason = " ".join(x for x in parts if x)
            if not reason:
                k, above = i - 1, []
                while k >= 0 and lines[k].strip().startswith("#"):
                    above.insert(0, lines[k].strip()[1:].strip())
                    k -= 1
                reason = " ".join(above)
            value = ast.get_source_segment(src, node.value) or ""
            rows.append((str(f.relative_to(pkg)), node.lineno, names[0], " ".join(value.split()), reason))
    return rows


def params_rows() -> list:
    """[(module, line, field, default, reason)] of the satellite engine's Params (sat/params.REASON)."""
    from .sat.params import REASON, Params
    return [("sat/params.py (Params)", 0, f.name, repr(f.default), REASON.get(f.name, "")) for f in fields(Params)]


def mark(reason: str, module: str) -> str:
    r = reason.lower()
    if module.endswith("plot.py") or r.startswith("layout"):
        return "layout"
    tags = [t for t in ("heuristic", "prior") if re.search(rf"\b{t}\b", r)]
    return ", ".join(tags)


def markdown(rows: list) -> str:
    head = ("# Constants\n\nEvery numeric constant cenfuse decides with, as the code states it: module, name, value, reason, and "
            "a mark for the named heuristics, the absolute priors and figure layout. Generated from the code by "
            "`python -m cenfuse.consts docs/constants.md` (cenfuse/consts.py); do not edit by hand. The curated summary is "
            "[design.md, Constants](design.md#constants).\n\n")
    out, mod = [head], None
    for m, _, name, value, reason in rows:
        if m != mod:
            out.append(f"\n## `{m}`\n\n| constant | value | reason | mark |\n|---|---|---|---|\n")
            mod = m
        cell = lambda x: x.replace("|", "\\|")
        out.append(f"| `{name}` | `{cell(value)}` | {cell(reason)} | {mark(reason, m)} |\n")
    return "".join(out)


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = markdown(scan() + params_rows())
    if argv:
        Path(argv[0]).write_text(text)
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
